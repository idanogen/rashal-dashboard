/**
 * שתי אותיות ואחריהן ספרות.
 *
 * ⭐ **וזה גם מה שמסנן טיוטות, במקרה ולטובה.** מסמך בטיוטה בפריוריטי
 * מקבל מספר זמני של אות אחת ומספר רץ (`T14388` בחשבונית, `T20` בתעודת
 * משלוח, `T57247` בחשבונית מרכזת), והוא לא עומד בצורה הזאת. כלומר על
 * שורת טיוטה השדה נשאר ריק, והעובד נדרש להקליד. מסמך טיוטה אינו מסמך
 * שאמור לצאת ללקוח.
 */
export const DOC_NUMBER = /^[A-Z]{2}\d{5,9}$/;

export interface DocPrefill {
  subject: string;
  doc_type: string;
  doc_number: string;
  /** false = המסך אינו מוכר לנו. משמש לרישום גילוי, לא לחסימה. */
  known_form: boolean;
}

/**
 * המסמך של השורה, מתוך כל הערכים שהתוסף ראה עליה.
 * **מחזיר מספר ריק כשיש ספק.**
 */
export function pickDocument(rawForm: unknown, candidates: string[]): DocPrefill {
  const form = String(rawForm ?? '').trim().toUpperCase();
  const shaped = [...new Set(candidates.filter((c) => DOC_NUMBER.test(c)))];

  const prefixes = DOC_PREFIX_BY_FORM[form];
  let number = '';
  if (prefixes) {
    const exact = shaped.filter((c) => prefixes.some((p) => c.startsWith(p)));
    // בדיוק אחד. שניים פירושם שהשורה מציגה שני מסמכים מאותה משפחה,
    // למשל חשבונית זיכוי לצד החשבונית שהיא מזכה, וזה לא מקרה לנחש בו.
    number = exact.length === 1 ? exact[0] : '';
  } else {
    // מסך שלא מיפינו: אין קידומת לסנן לפיה, ולכן רק מספר אחד בשורה כולה
    // נחשב ודאי. שניים ומעלה מחזירים ריק.
    number = shaped.length === 1 ? shaped[0] : '';
  }

  return {
    subject: SUBJECT_BY_FORM[form] ?? 'הפנייה',
    doc_type: DOC_TYPE_BY_PREFIX[number.slice(0, 2)] ?? DOC_TYPE_BY_FORM[form] ?? '',
    doc_number: number,
    known_form: Boolean(SUBJECT_BY_FORM[form] || DOC_TYPE_BY_FORM[form]),
  };
}
