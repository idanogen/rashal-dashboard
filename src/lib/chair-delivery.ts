export function canSubmitChairDelivery(v: Pick<ChairDeliveryValues, 'userSignature' | 'driverSignature'>): {
  ok: boolean;
  reason?: string;
} {
  if (!v.userSignature) return { ok: false, reason: 'חסרה חתימת המשתמש או בא כוחו' };
  if (!v.driverSignature) return { ok: false, reason: 'חסרה חתימת המוסר' };
  return { ok: true };
}

/** היצרן מתוך תיאור הפריט בהזמנה ("... תוצרת PRIDE", "... SUNRISE MEDICAL"). ריק כשלא ידוע. */
export function manufacturerFromDesc(desc: string | null | undefined): string {
  const d = desc ?? '';
  const m = d.match(/תוצרת\s+([A-Za-z][A-Za-z ]*[A-Za-z]|[א-ת"]+)/);
  if (m) return m[1].trim();
  if (/PRIDE/i.test(d)) return 'PRIDE';
  if (/SUNRISE/i.test(d)) return 'SUNRISE MEDICAL';
  return '';
}

/** שם קובץ בפריוריטי. 🔴 נחתך ב-60 תווים (`api/priority-push`), לכן קצר. */
export function chairDeliveryFileDes(customerName: string, signedAt: Date): string {
  const two = (n: number) => String(n).padStart(2, '0');
  const date = `${two(signedAt.getDate())}.${two(signedAt.getMonth() + 1)}.${String(signedAt.getFullYear()).slice(2)}`;
  return `הוראות ובטיחות ממונע ${customerName}`.slice(0, 48).trim() + ` ${date}`;
}
