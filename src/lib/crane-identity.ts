/** `G` + שלוש ספרות + `E` אופציונלי. G175 · G150E · G130 · G165. */
export const CRANE_MODEL_RE = /^G\d{3}E?$/i;

export function isCraneModel(name: string | null | undefined): boolean {
  return CRANE_MODEL_RE.test((name ?? '').trim());
}

export interface OrderLine {
  part?: string | null;
  desc?: string | null;
  serial?: string | null;
}

/**
 * המנוף שבתוך הזמנה, אם יש.
 *
 * 🔴 **לפי המק״ט בלבד ולא לפי התיאור.** התיאור מכיל את המילה "מנוף" גם
 * בשורות שאינן מנוף: ערסל למנוף (4,500 שורות), השתתפות עצמית בגין
 * רכישת מנוף (3,000), זמן עבודה בתיקון מנוף, גלגל, שלט. התאמה על
 * המילה הייתה מפעילה טופס הדרכה על אספקת ערסל בודד.
 *
 * ⭐ מוחזר גם המספר הסידורי, כי הוא מה שנשמר על הטופס החתום ומה שיאפשר
 * למצוא אותו שוב בעוד שלוש שנים כשתגיע הבדיקה התקופתית.
 */
export function craneInOrder(items: OrderLine[] | null | undefined): OrderLine | null {
  if (!items) return null;
  return items.find((i) => isCraneModel(i.part)) ?? null;
}
