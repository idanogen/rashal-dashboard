/**
 * מה נשלח לשירות המיפוי בתור "כתובת".
 *
 * 🔴 **הבאג שזה סוגר (25/10/2026, בדיקת המוכנות לפגישה עם עמי).** הדשבורד
 * שלח רק את הרחוב ("קרן היסוד 16"), והעיר נסעה בפרמטר נפרד שהשירות משתמש
 * בו רק לאימות. גוגל מיקם את הרחוב בעיר אחרת, האימות ראה שהעיר לא מתאימה
 * ופסל, והנקודה נפלה למרכז העיר. כך נכשלו כ-45% מהכתובות במשך שבועות. עם
 * העיר בתוך השאילתה, כל ארבע הכתובות שנבדקו חזרו מדויקות.
 *
 * ⭐ העיר לא מוכפלת כשהכתובת כבר מכילה אותה ("סמילנסקי 21 נתניה").
 * הקובץ בלי ייבוא, כדי שייבדק ביחידה.
 */
export function geocodeQuery(address: string, city?: string | null): string {
  const a = address.trim();
  const c = (city ?? '').trim();
  if (!c) return a;
  const norm = (s: string) => s.replace(/[-־"'״׳\s]+/g, '');
  if (norm(a).includes(norm(c))) return a;
  return `${a}, ${c}`;
}
