-- ═══════════════════════════════════════════════════════════════
--
-- 🔴🔴 **הבאג שעמי דיווח עליו (26/08/2026):** "לקוח קיים פתח קריאה
-- לביטול עסקה, לבוא לאסוף משהו שסיפקתי לו לפני שבוע, והמערכת לא נותנת
-- לי לשבץ. זה לא אחד ולא שתיים."
--
-- **השורש:** המדד הייחודי מונע שני שיבוצים פעילים לאותו לקוח, והמפתח
-- שלו הוא שם + טלפון + כתובת + עיר **בלי סוג העצירה**. כלומר אספקה
-- ואיסוף לאותו לקוח נחשבים לאותו דבר, ואחד מהם חוסם את השני, למרות
-- שאלה שתי עבודות שונות לחלוטין.
--
-- ⭐ **והמכפיל הוא השאריות:** 294 מתוך 299 העצירות ה"פעילות" מתוארכות
-- לעבר, 236 מהן מעל חודש, הוותיקה מ-22/04. האספקה שכבר בוצעה נשארה
-- `planned` כי איש לא סגר אותה, **והיא ממשיכה לחסום לנצח**.
--
-- **נמדד לפני השינוי (26/08/2026):** 45 איסופים + 27 הזמנות + 13 קריאות
-- שירות פתוחים, סך הכל **85 פריטים שאי אפשר לשבץ היום**.
--
-- 🔴 **מה ההגנה עדיין עושה, ובכוונה:** שתי אספקות לאותו לקוח עדיין
-- נחסמות, וכך גם שתי קריאות שירות. זו הייתה הכוונה המקורית ("לא לשלוח
-- פעמיים נהג לאותו לקוח"), והיא נשמרת במלואה. מה שהשתנה הוא רק שסוגים
-- שונים מפסיקים להתנגש זה בזה.
--
-- ⭐ המדד החדש **מתירני יותר** מהישן, ולכן אין שום סיכוי לשורה קיימת
-- שתפר אותו, ואין צורך בניקוי מקדים.

begin;

-- 1. המדד החדש נוצר לפני שהישן יורד, כדי שלא יהיה רגע בלי הגנה בכלל.
create unique index if not exists calendar_stops_no_active_dup_v2
  on public.calendar_stops (
    source_type,
    lower(coalesce(customer_name, '')),
    coalesce(phone, ''),
    coalesce(address, ''),
    coalesce(city, '')
  )
  where status in ('planned', 'in_progress');

-- 2. ורק עכשיו הישן.
drop index if exists public.calendar_stops_no_active_dup;

commit;

comment on index public.calendar_stops_no_active_dup_v2 is
  'שיבוץ פעיל אחד לכל לקוח לכל סוג עצירה. סוג העצירה במפתח מ-26/08/2026, אחרי שאספקה חסמה איסוף לאותו לקוח.';
