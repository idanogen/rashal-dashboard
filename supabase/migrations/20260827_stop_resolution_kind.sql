-- "המשך טיפול": מצב אמיתי בשטח שלא היה לו כפתור
-- ═══════════════════════════════════════════════════════════════
--
-- 🔴🔴 **עמי, 26/08/2026:** "לפעמים אתה מספק כיסא גלגלים ושולחים לך
-- חגורה, והחגורה לא מתאימה. הבחור בשטח הוא זה שמקבל את ההחלטה. אנחנו
-- צריכים להוסיף לו כפתור של המשך טיפול, ואז הוא מעדכן אותנו."
--
-- **מה שהיה עד היום:** לנהג היו שני כפתורים בלבד, "בוצע" ו"לא בוצע".
-- אספקה שיצאה והסתיימה חלקית איננה אף אחד מהם, ולכן **הוא לא לחץ כלום**,
-- והעצירה נשארה `planned` לנצח.
--
-- ⭐ **וזה בדיוק המנגנון שמייצר את השאריות:** 294 מתוך 299 העצירות
-- ה"פעילות" מתוארכות לעבר, 236 מהן מעל חודש. הן לא נשכחו, פשוט לא היה
-- מה ללחוץ כדי לתאר את המציאות. **מצב אמיתי בשטח בלי כפתור במסך מייצר
-- שאריות, לא שגיאות.**
--
-- 🔴 **למה עמודה ולא סטטוס חדש.** `not_completed` כבר עושה בדיוק את מה
-- שצריך: סוגר את העצירה (ולכן היא מפסיקה לחסום שיבוץ חדש), ומחזיר את
-- המקור לרשימת הממתינים עם הסיבה. סטטוס שישי היה נוגע ב-22 קבצים
-- שמסתעפים על הסטטוס, וכל אחד מהם הזדמנות לשכוח ענף. מה שבאמת חסר הוא
-- **להבדיל בין "לא הגעתי" לבין "הגעתי, וצריך המשך"**, וזו עמודה אחת.

alter table public.calendar_stops
  add column if not exists resolution_kind text
    check (resolution_kind in ('not_done', 'follow_up'));

comment on column public.calendar_stops.resolution_kind is
  'איך נסגרה עצירה שלא הושלמה: not_done = לא בוצע כלל · follow_up = בוצע חלקית ונדרש המשך טיפול. NULL בעצירות שנסגרו לפני 27/08/2026.';

-- ⭐ אינדקס חלקי: המסכים שואלים "מי ממתין להמשך טיפול", וזו שאלה על
-- מיעוט קטן מתוך העצירות. אינדקס מלא היה מבזבז מקום על השאר.
create index if not exists calendar_stops_follow_up_idx
  on public.calendar_stops (resolution_kind, delivery_date desc)
  where resolution_kind = 'follow_up';
