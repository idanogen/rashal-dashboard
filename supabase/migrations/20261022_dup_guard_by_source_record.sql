-- ⭐ **המפתח החדש כולל את המסמך** (הזמנה / קריאה / איסוף / בדיקה). אותו
-- מסמך פעמיים עדיין נחסם, וגם עצירות בלי מסמך (לקוח חדש, משימה)
-- מתנהגות בדיוק כמו קודם, כי אצלן הרכיב ריק.
