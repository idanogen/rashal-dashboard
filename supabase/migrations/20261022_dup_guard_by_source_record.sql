-- האזהרה בדפדפן נשארת: הדיאלוג מציג את השיבוץ הקיים ומציע "שבץ גם את
-- זה", כדי ששארית ישנה עדיין תתגלה ותיסגר ולא תיערם בשקט.
--
-- ⭐ המדד החדש מתירני יותר מהישן, ולכן אין שורה קיימת שתפר אותו.

begin;

create unique index if not exists calendar_stops_no_active_dup_v3
  on public.calendar_stops (
    source_type,
    lower(coalesce(customer_name, '')),
    coalesce(phone, ''),
    coalesce(address, ''),
    coalesce(city, ''),
    coalesce(order_id::text, service_call_id::text, pickup_id::text, inspection_id::text, '')
  )
  where status in ('planned', 'in_progress');

drop index if exists public.calendar_stops_no_active_dup_v2;

commit;

comment on index public.calendar_stops_no_active_dup_v3 is
  'שיבוץ פעיל אחד לכל לקוח, לכל סוג עצירה, לכל מסמך. המסמך במפתח מ-22/10/2026, אחרי ששני איסופים לאותו לקוח (מנוף וכיסא) נחסמו.';
