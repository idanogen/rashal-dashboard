--
-- **השורש:** `calendar_stops_no_active_dup_v2` (26/08) מרשה עצירה פעילה
-- אחת ללקוח לכל סוג, בלי קשר למסמך. שני מסמכי איסוף שונים הם עבודה
-- אמיתית ולא כפילות. נמדד 22/10: כ-13 לקוחות עם יותר מאיסוף פתוח אחד.
